import {test,expect} from '@playwright/test';
import {randomUUID} from 'node:crypto';

test('signup, save on assessment only, signin restores inputs, and accounts stay separate',async({page})=>{
  const email='auth-'+randomUUID()+'@example.com';
  const password='test-password-2026';
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'Welcome back.'})).toBeVisible();
  await page.getByRole('button',{name:'Sign up',exact:true}).click();
  await page.getByLabel('Email address').fill(email);
  await page.getByLabel('Password',{exact:true}).fill(password);
  await page.getByLabel('Confirm password').fill(password);
  await page.getByRole('button',{name:'Create account',exact:true}).click();
  await expect(page.getByText('Models ready')).toBeVisible();
  await page.locator('#field-Age').fill('58');
  await page.locator('#field-Obesity').selectOption('Y');
  expect((await (await page.request.get('/api/session')).json()).inputs).toBeNull();
  await page.getByRole('button',{name:'Run assessment'}).click();
  await expect(page.getByText('Assessment complete',{exact:true})).toBeVisible();
  const saved=(await (await page.request.get('/api/session')).json()).inputs;
  expect(Object.keys(saved)).toHaveLength(55);
  expect(saved.Age).toBe(58);expect(saved.Obesity).toBe('Y');
  await page.locator('#field-Age').fill('67');
  expect((await (await page.request.get('/api/session')).json()).inputs.Age).toBe(58);
  await page.getByRole('button',{name:'Sign out',exact:true}).click();
  await page.getByLabel('Email address').fill(email);
  await page.getByLabel('Password',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await expect(page.locator('#field-Age')).toHaveValue('58');
  await expect(page.locator('#field-Obesity')).toHaveValue('Y');
  await page.locator('#field-Age').fill('65');
  await page.getByRole('button',{name:'Run assessment'}).click();
  await expect(page.getByText('Assessment complete',{exact:true})).toBeVisible();
  await page.reload();
  await expect(page.locator('#field-Age')).toHaveValue('65');
  expect(await page.evaluate(()=>document.cookie)).not.toContain('coronary_session');
  const rejected=await page.request.post('/api/predict',{headers:{Origin:'https://unrelated.example'},data:{values:saved}});
  expect(rejected.status()).toBe(403);
  await page.getByRole('button',{name:'Sign out',exact:true}).click();
  await page.getByRole('button',{name:'Sign up',exact:true}).click();
  await page.getByLabel('Email address').fill('other-'+randomUUID()+'@example.com');
  await page.getByLabel('Password',{exact:true}).fill(password);
  await page.getByLabel('Confirm password').fill(password);
  await page.getByRole('button',{name:'Create account',exact:true}).click();
  await expect(page.getByText('Models ready')).toBeVisible();
  expect((await (await page.request.get('/api/session')).json()).inputs).toBeNull();
  await expect(page.locator('#field-Age')).not.toHaveValue('65');
});

test('signup and signin fit on a phone',async({page})=>{
  await page.setViewportSize({width:390,height:844});
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'Welcome back.'})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.screenshot({path:'test-results/auth-mobile.png',fullPage:true});
  await page.getByRole('button',{name:'Sign up',exact:true}).click();
  await expect(page.getByLabel('Confirm password')).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
});
